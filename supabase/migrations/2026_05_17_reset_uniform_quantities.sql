-- =============================================================================
-- بَعد التَحَوُّل لِنَموذَج "الكاتالوج يُعَرِّف الصَنف فَقَط + فَواتير الاستِلام
-- تَزيد المَخزون عَبر trigger"، يَجِب تَصفير أَيّ كَمّيّات قَديمة كانَت قَد
-- أُدخِلَت يَدويّاً في حَقل uniform_items.quantity حَتّى لا تَظهَر كَمَخزون
-- وَهميّ في الواجِهة.
--
-- بَعد هَذا التَنفيذ:
--   • كُلّ أَصناف الكاتالوج تَبدَأ بِـ 0
--   • أَيّ فاتورة استِلام جَديدة (uniform_purchases) تَزيد quantity تِلقائيّاً
--   • أَيّ صَرف (employee_uniforms) يُنقِص quantity تِلقائيّاً
-- =============================================================================

UPDATE uniform_items
SET quantity = 0
WHERE quantity IS NOT NULL;

-- تَأكيد
SELECT
  COUNT(*) AS total_items,
  SUM(quantity) AS total_qty_should_be_zero
FROM uniform_items;
