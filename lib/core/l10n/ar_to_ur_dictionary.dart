/// تَرجَمة سَريعة عَرَبيّ → أردو
/// تُعيد النَص الأَردويّ لَو وُجِد في القاموس، وَإلّا تُعيد العَرَبيّ.
/// تُتَجاهَل المُفرَدات الفارِغة وَالأرقام.
String translateArToUr(String arText) {
  if (arText.isEmpty) return arText;
  // الجَدول الكامِل
  final exact = kArToUrDictionary[arText];
  if (exact != null) return exact;
  // مُحاوَلة استبدال الكَلِمات الفرديّة المَعروفة في النَص
  // (تَتَخَطّى أَرقام وَرُموز خاصّة)
  var result = arText;
  kArToUrDictionary.forEach((ar, ur) {
    if (result.contains(ar)) {
      result = result.replaceAll(ar, ur);
    }
  });
  return result;
}

/// 🌍 لُغة عالَميّة - مُحَدَّثة مِن `LocaleProvider` عَنَد التَبديل.
/// تُتيح لِـ`tr()` العَمَل بِدون BuildContext.
String _activeLanguageCode = 'ar';

/// تُحدَّث مِن `LocaleProvider.setLocale()` لِكَي يَعمَل `tr()` تِلقائيّاً.
void setGlobalLanguageCode(String code) {
  _activeLanguageCode = code;
}

/// 🔄 تَرجَمة عالَميّة بِدون BuildContext.
/// تَستَخدِم اللُغة العالَميّة المَحفوظة وَتُتَرجِم العَرَبيّ إلى أَردو لَو لَزِم.
/// **مِثال:** `Text(tr('صباح الخير'))` يُظهِر "صبح بخیر" لِمُستَخدِم الأردو.
String tr(String text) {
  if (_activeLanguageCode == 'ur') {
    return translateArToUr(text);
  }
  return text;
}
